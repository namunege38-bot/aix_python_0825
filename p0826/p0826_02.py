# 변수 타입
# 변수 : 값을 저장하는 공간

# 파이썬의 기본 자료형
# 숫자형 타입(정수형, 실수형)
# 문자열 타입
# 불 타입(bool)

# int   : 정수형
# float : 실수형
# str   : 문자열
# bool  : 불 타입

# 정수형(int) - 1, 2, 3
# 소수점이 없는 숫자

# 실수형(float) - 1.1, 2.2, 3.14
# 소수점이 있는 숫자

# 문자열(str) - "안녕", '111', "Hello"
# 큰따옴표("") 또는 작은따옴표('')로 감싸서 표현

# 불 타입(bool) - True, False
# 반드시 첫 글자를 대문자로 작성
# true, false, flase 등은 사용할 수 없음


# ----------------------------------------
# 변수의 타입 확인
# ----------------------------------------

# type(변수)를 사용하면 변수의 자료형을 확인할 수 있음

a = 10
print(type(a))       # <class 'int'>

b = 3.14
print(type(b))       # <class 'float'>

c = "안녕"
print(type(c))       # <class 'str'>

d = True
print(type(d))       # <class 'bool'>


# ----------------------------------------
# 변수 이름 규칙
# ----------------------------------------

# 1. 영문자, 숫자, 밑줄(_)을 사용할 수 있음
# 2. 숫자로 시작할 수 없음
# 3. 특수문자는 사용할 수 없음
# 4. 파이썬의 예약어는 변수 이름으로 사용할 수 없음
# 5. 대문자와 소문자는 구분됨


# 올바른 변수 이름

a = 10
_a = 10
a_1 = 10
a_1_2_b = 10
aBBa = 1
Aa = 1
a11111 = 1


# ----------------------------------------
# 잘못된 변수 이름
# ----------------------------------------

# 숫자가 제일 앞에 오는 경우
# 1_a = 10       # 에러

# 특수문자를 사용하는 경우
# a@ = 10        # 에러
# a-b = 10       # 에러
# a b = 10       # 에러


# ----------------------------------------
# 예약어
# ----------------------------------------

# 파이썬에서 이미 명령어로 사용하는 단어는
# 변수 이름으로 사용할 수 없음.

# 예:
# if = 10        # 에러
# for = 10       # 에러
# class = 10     # 에러
# def = 10       # 에러


# True와 False도 예약된 값이므로
# 변수 이름으로 사용할 수 없음.

# True = 1       # 에러
# False = 0      # 에러


# ----------------------------------------
# 대문자와 소문자는 서로 다른 변수
# ----------------------------------------

a = 10
A = 20

print(a)         # 10
print(A)         # 20