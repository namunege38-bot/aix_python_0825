# ----------------------------------------
# 원의 반지름을 입력받아 원의 넓이 출력
# ----------------------------------------

# 원의 넓이 = 원주율 × 반지름²
# π(파이) = 3.14

length = int(input("반지름을 입력하시오: "))
pi = 3.14

result = pi * (length ** 2)

print("원의 넓이 : {}cm²".format(result))


# ----------------------------------------
# 원의 둘레
# ----------------------------------------

# 원의 둘레 = 2 × π × 반지름

circumference = 2 * pi * length

print("원의 둘레 : {}cm".format(circumference))


