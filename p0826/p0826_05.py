# ----------------------------------------
# 학생 정보를 입력받아 합계와 평균 출력
# ----------------------------------------

# 번호, 이름, 국어, 영어, 수학을 입력받아
# 번호, 이름, 국어, 영어, 수학, 합계, 평균을 출력하시오.
#
# 예시
# 1 홍길동 100 100 100 300 100.0
# 2 유관순 100 100 91 291 97.0


# 첫 번째 학생

no = input("번호 입력>> ")
name = input("이름 입력>> ")
kor = int(input("국어점수 입력>> "))
eng = int(input("영어점수 입력>> "))
math = int(input("수학점수 입력>> "))

total = kor + eng + math
avg = total / 3


# 두 번째 학생

no2 = input("번호 입력>> ")
name2 = input("이름 입력>> ")
