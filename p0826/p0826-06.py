# ----------------------------------------
# 관계 연산자
# ----------------------------------------

# == : 같다
# != : 같지 않다
# >  : 크다
# <  : 작다
# >= : 크거나 같다
# <= : 작거나 같다

# 관계 연산의 결과는 True 또는 False
# True, False는 bool 타입


a = 10
b = 5

print(a == b)    # False
print(a != b)    # True
print(a > b)     # True
print(a < b)     # False
print(a >= b)    # True
print(a <= b)    # False


