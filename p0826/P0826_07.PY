# ----------------------------------------
# 비트 연산자 &
# ----------------------------------------

# & : AND 연산
# 두 숫자를 2진수로 변환한 후
# 같은 자리의 비트가 모두 1이면 1
# 하나라도 0이면 0


print(10 & 7)


# ----------------------------------------
# 10을 2진수로 변환
# ----------------------------------------

print(bin(10))


# ----------------------------------------
# 7을 2진수로 변환
# ----------------------------------------

print(bin(7))