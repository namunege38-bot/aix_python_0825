# ----------------------------------------
# 국어, 영어, 수학 점수
# ----------------------------------------

# 국어, 영어, 수학 점수를 입력받아
# 합계와 평균을 출력하시오.
#
# 예시
# 국어 : 100
# 영어 : 100
# 수학 : 100
# 합계 : 300
# 평균 : 100.0

name = "홍길동"

kor = int(input("국어점수를 입력하세요: "))
eng = int(input("영어점수를 입력하세요: "))
math = int(input("수학점수를 입력하세요: "))

total = kor + eng + math
avg = total / 3

print("이름 : {}".format(name))
print("합계 : {}, 평균 : {}".format(total, avg))


# ----------------------------------------
# 10진수를 2진수로 변경
# ----------------------------------------

# bin()을 사용하면 10진수를 2진수로 변경할 수 있음

print(bin(5))

# 결과
# 0b101
#
# 0b에서 b는 binary(2진수)를 의미함.


# ----------------------------------------
# 2진수를 10진수로 변경
# ----------------------------------------

# int("2진수", 2)를 사용
# 두 번째 값 2는 해당 숫자가 2진수라는 의미

print(int("101", 2))

# 결과
# 5


