# 아이디와 패스워드를 입력받아 출력하시오.
# 아이디: aaa
# 패스워드: 1111

id = input("아이디를 입력하세요: ")
pw = input("패스워드를 입력하세요: ")

# 입력받은 아이디가 "aaa"와 같은지 확인
print("아이디 확인 : {}".format("aaa" == id))

# 입력받은 패스워드가 "1111"과 같은지 확인
print("패스워드 확인 : {}".format("1111" == pw))

# 입력받은 아이디와 패스워드 출력
print("아이디:{}, 패스워드:{}".format(id, pw))